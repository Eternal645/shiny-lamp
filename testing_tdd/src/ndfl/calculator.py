"""
Расчёт НДФЛ по прогрессивной шкале РФ (с 2025 года).

Шкала ставок:
  До 2 400 000 руб.          — 13%
  2 400 000 – 5 000 000      — 15% (с суммы превышения)
  5 000 000 – 20 000 000     — 18% (с суммы превышения)
  20 000 000 – 50 000 000    — 20% (с суммы превышения)
  Свыше 50 000 000           — 22% (с суммы превышения)
"""

# Пороговые значения и ставки
_BRACKETS = [
    (2_400_000,  0.13,         0),
    (5_000_000,  0.15,   312_000),
    (20_000_000, 0.18,   702_000),
    (50_000_000, 0.20, 3_402_000),
    (float("inf"), 0.22, 9_402_000),
]


def calculate_tax(income: float) -> float:
    """
    Рассчитывает НДФЛ для заданного годового дохода.

    Args:
        income: Годовой доход в рублях (неотрицательное число).

    Returns:
        Сумма налога в рублях.

    Raises:
        ValueError: Если доход отрицательный.

    Examples:
        >>> calculate_tax(200_000)
        26000.0
        >>> calculate_tax(3_000_000)
        402000.0
        >>> calculate_tax(7_000_000)
        1062000.0
    """
    if income < 0:
        raise ValueError(f"Доход не может быть отрицательным: {income}")

    prev_limit = 0
    for limit, rate, base_tax in _BRACKETS:
        if income <= limit:
            return base_tax + (income - prev_limit) * rate
        prev_limit = limit

    return 0.0
